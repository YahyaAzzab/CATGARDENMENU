export function pickLabeled(locale, row, base) {
    const suffix = locale === 'en' ? 'En' : locale === 'ar' ? 'Ar' : 'Fr';
    const record = row;
    return record[`${base}${suffix}`] || record[`${base}Fr`] || '';
}
export function getTagLabel(tag, locale) {
    const key = `tag${tag.charAt(0).toUpperCase() + tag.slice(1)}`;
    const t = translations[locale];
    const val = t[key];
    return typeof val === 'string' ? val : tag;
}
export function getBadgeLabel(badge, locale) {
    const key = `badge${badge.charAt(0).toUpperCase() + badge.slice(1)}`;
    const t = translations[locale];
    const val = t[key];
    return typeof val === 'string' ? val : badge;
}
